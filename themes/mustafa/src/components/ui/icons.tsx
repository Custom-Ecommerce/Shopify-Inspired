import type { SVGProps } from "react";
import { cn } from "./cn";

type IconProps = SVGProps<SVGSVGElement>;

/**
 * Base for the theme icons: a 24px grid, stroked in currentColor, hidden from assistive technology.
 * Icons are 20px unless the caller passes its own size class.
 */
function Icon({ className, children, ...props }: IconProps) {
  const sized = className !== undefined && /(^|\s)size-/.test(className);
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
      className={cn(sized ? undefined : "size-5", "shrink-0", className)}
    >
      {children}
    </svg>
  );
}

